def write(path, text):
    with open(path, "w", encoding="utf-8") as handle:
        handle.write(text.strip() + "\n")


def four(value):
    return f"{float(value):.4f}"


def percent(value):
    return f"{float(value) * 100:.2f}%"


def comma(value):
    return f"{int(value):,}"


def leader_sentence(rows, key, label):
    best = max(float(row[key]) for row in rows)
    names = [row["model"] for row in rows if abs(float(row[key]) - best) < 1e-9]
    joined = names[0] if len(names) == 1 else " and ".join(names)
    return (
        "The highest validation "
        + label
        + " was "
        + four(best)
        + " ("
        + percent(best)
        + "), from "
        + joined
        + "."
    )


def comparison_table(rows):
    lines = [
        "| Model | Accuracy | Precision | Recall | F1 |",
        "|---|---:|---:|---:|---:|",
    ]
    for row in rows:
        lines.append(
            "| "
            + row["model"]
            + " | "
            + four(row["accuracy"])
            + " | "
            + four(row["precision"])
            + " | "
            + four(row["recall"])
            + " | "
            + four(row["f1"])
            + " |"
        )
    return "\n".join(lines)


def hyperparameter_lines(settings):
    lines = []
    for name, value in settings.items():
        lines.append("- " + name + ": " + str(value))
    return "\n".join(lines)


def safe_cell(text):
    return str(text).replace("|", "/").replace("\n", " ")


